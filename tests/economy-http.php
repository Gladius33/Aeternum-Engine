<?php
declare(strict_types=1);
use Aeternum\Core\{EconomyHttpApi,GamePackLoader,PdoScheduler,PdoMemberships,PdoSessions,FrozenClock};
$ec=new FrozenClock(500);
$er=GamePackLoader::load(file_get_contents(__DIR__.'/../games/reference-medieval/manifest.json'))->rules();
$ew='http-economy';
(new PdoScheduler(db(),$ew,$ec,$er))->initialize();
$em=new PdoMemberships(db(),$ew);
$em->grant($actor); $em->assign('mine',$actor);
$et=(new PdoSessions(db(),$ec))->login('test-player','correct horse battery staple');
$ea=new EconomyHttpApi(db(),$ec,[$ew=>$er]);
$ep='/v1/worlds/'.$ew.'/economy/';
$eh='Bearer '.$et;
$eb=json_encode(['id'=>'open','type'=>'economy.open','payload'=>['account'=>'mine','resource'=>'wood']],JSON_THROW_ON_ERROR);
check($ea->handle('POST',$ep.'commands','',$eb)[0]===401,'economy HTTP auth required');
[$st,$br]=$ea->handle('POST',$ep.'commands',$eh,$eb);
check($st===200,'economy HTTP command');
check($ea->handle('POST',$ep.'commands',$eh,$eb)[1]==$br,'economy HTTP retry');
[$st,$br]=$ea->handle('GET',$ep.'balances/mine/wood',$eh);
check($st===200&&$br['data']->stock===100,'economy HTTP balance');
check($ea->handle('GET',$ep.'balances/other/wood',$eh)[0]===409,'economy HTTP foreign account');
check($ea->handle('POST',$ep.'commands',$eh,'{}')[0]===400,'economy HTTP invalid payload');
$eo=$ep.'overview/mine/wood';
check($ea->handle('GET',$eo,'')[0]===401,'overview requires authentication');
check($ea->handle('POST',$eo,$eh)[0]===405,'overview is read only');
[$st,$br]=$ea->handle('GET',$eo,$eh);
check($st===200&&$br['data']['stock']===100&&$br['data']['level']===0&&$br['data']['pending']===null,'overview initial snapshot');
check($br['data']['next']===['level'=>1,'cost'=>40,'duration'=>120,'amount'=>50],'overview next upgrade rules');
check($ea->handle('GET',$ep.'overview/other/wood',$eh)[0]===409,'overview denies foreign account');
check($ea->handle('GET',$ep.'overview/mine/nonexistent',$eh)[0]===409,'overview denies unknown resource');
check($ea->handle('GET','/v1/worlds/not-configured/economy/overview/mine/wood',$eh)[0]===404,'overview denies unconfigured world');
$eu=json_encode(['id'=>'upgrade','type'=>'economy.upgrade','payload'=>['account'=>'mine','resource'=>'wood']],JSON_THROW_ON_ERROR);
check($ea->handle('POST',$ep.'commands',$eh,$eu)[0]===200,'overview fixture upgrade');
[$st,$br]=$ea->handle('GET',$eo,$eh);
check($st===200&&$br['data']['stock']===60&&$br['data']['level']===0&&$br['data']['next']===null,'overview pending debit');
check($br['data']['pending']===['level'=>1,'dueAt'=>620,'amount'=>50],'overview exposes real due time without event identifier');
$ec->advanceTo(620);
check($ea->handle('GET',$eo,$eh)[0]===409,'overview preserves due-event barrier');
(new PdoScheduler(db(),$ew,$ec,$er))->processDue($er->events);
[$st,$br]=$ea->handle('GET',$eo,$eh);
check($st===200&&$br['data']['level']===1&&$br['data']['pending']===null&&$br['data']['next']['level']===2,'overview completed level');
$em->revoke($actor);
check($ea->handle('GET',$ep.'balances/mine/wood',$eh)[0]===409,'economy HTTP revoked membership');
check($ea->handle('GET',$eo,$eh)[0]===409,'overview revoked membership');
