<?php
declare(strict_types=1);
use Aeternum\Core\{PdoScheduler,PdoMemberships,FrozenClock,GamePackLoader,Command,ActorReceipt};

$actorClock=new FrozenClock(100);
$actorRules=GamePackLoader::load(file_get_contents(__DIR__.'/../games/reference-medieval/manifest.json'))->rules();
$aw='actors';
$as=new PdoScheduler(db(),$aw,$actorClock,$actorRules);
$as->initialize();
$members=new PdoMemberships(db(),$aw);
$members->grant('alice'); $members->grant('bob');
$members->assign('a','alice'); $members->assign('b','bob');
$members->assign('a','alice');
rejects(fn()=> $members->assign('a','bob'),DomainException::class,'account reassignment rejected');
rejects(fn()=> $members->assign('c','outsider'),DomainException::class,'inactive actor assignment denied');
$acmd=fn(string $id,string $type,array $payload)=>new Command($aw,$id,$type,$payload);
$openA=$acmd('open','economy.open',['account'=>'a','resource'=>'wood']);
$openB=$acmd('open','economy.open',['account'=>'b','resource'=>'wood']);
rejects(fn()=> $as->executeForActor('outsider',$openA,$actorRules->commands),DomainException::class,'nonmember denied');
rejects(fn()=> $as->executeForActor('bob',$openA,$actorRules->commands),DomainException::class,'cannot open another account');
$aReceipt=$as->executeForActor('alice',$openA,$actorRules->commands);
$bReceipt=$as->executeForActor('bob',$openB,$actorRules->commands);
check($aReceipt instanceof ActorReceipt && $bReceipt->requestId==='open' && !property_exists($aReceipt,'state'),'actor receipt scopes IDs and excludes world state');
check($as->executeForActor('alice',$openA,$actorRules->commands)==$aReceipt,'actor retry idempotent');
rejects(fn()=> $as->executeForActor('alice',$acmd('open','economy.open',['account'=>'a','resource'=>'grain']),$actorRules->commands),DomainException::class,'actor conflicting retry rejected');
$t=$acmd('t1','economy.transfer',['from'=>'a','to'=>'b','resource'=>'wood','units'=>20]);
rejects(fn()=> $as->executeForActor('bob',$t,$actorRules->commands),DomainException::class,'cannot debit another actor');
$as->executeForActor('alice',$t,$actorRules->commands);
check($as->balanceForActor('alice','a','wood',$actorRules->commands)->stock===80 && $as->balanceForActor('bob','b','wood',$actorRules->commands)->stock===120,'authorized transfer and own balance read');
rejects(fn()=> $as->balanceForActor('alice','b','wood',$actorRules->commands),DomainException::class,'cannot read another actor balance');
$actorClock->advanceTo(101);
$up=$as->executeForActor('alice',$acmd('up','economy.upgrade',['account'=>'a','resource'=>'wood']),$actorRules->commands);
$actorClock->advanceTo(221);
rejects(fn()=> $as->balanceForActor('alice','a','wood',$actorRules->commands),DomainException::class,'read projection cannot overtake due upgrade');
check($as->processDue($actorRules->events)===$up->scheduledIds,'authorized upgrade completion processed');
$members->revoke('alice');
rejects(fn()=> $as->executeForActor('alice',$t,$actorRules->commands),DomainException::class,'revoked actor cannot replay receipt');
rejects(fn()=> $as->balanceForActor('alice','a','wood',$actorRules->commands),DomainException::class,'revoked actor cannot read balance');
rejects(fn()=> $as->executeForActor('bob',$acmd('to-revoked','economy.transfer',['from'=>'b','to'=>'a','resource'=>'wood','units'=>1]),$actorRules->commands),DomainException::class,'transfer to inactive member denied');
$members->grant('alice');
check($as->executeForActor('alice',$t,$actorRules->commands)->requestId==='t1','reactivated membership retains prior idempotency');
check($as->verifyReplay($actorRules->commands,$actorRules->events)->entries===5,'actor-scoped commands retain deterministic replay');
rejects(fn()=> $as->execute($acmd('actor:reserved','economy.settle',['account'=>'a','resource'=>'wood']),$actorRules->commands),InvalidArgumentException::class,'trusted intake reserves actor namespace');
rejects(fn()=> $as->executeForActor('alice',new Command('world-A','open','economy.open',['account'=>'a','resource'=>'wood']),$actorRules->commands),InvalidArgumentException::class,'cross-world actor request denied');
$actorRows=db()->query("SELECT COUNT(*) FROM engine_commands WHERE world_id='actors' AND actor_id IS NOT NULL")->fetchColumn();
check((int)$actorRows===4,'four admitted commands have durable actor audit metadata');
